  const sx=360+(i%4)*35,sz=240+(i%3)*25;
  const points=[[-.9,-.8],[-.5,-.8],[0,-.8],[.5,-.8],[.9,-.8],...tail].map(([x,z])=>[x*sx,z*sz]);
